def step2(lmin, lmax, cores=1, do_orbits=False, progress=True):
    for ell in range(lmin, lmax + 1):
        if ell % 2 == 0:                       # even ell: no LPs, T = 0
            if progress:
                print(f"[ell={ell}] even -> skip (T=0)")
            continue

        neg = (ell - 1) // 2
        M = math.comb(ell, neg)
        GG = group_order(ell)
        count, sigmap = census_signatures(ell, cores=cores, progress=progress)
        T_ordered, T_unordered, T_diag = totals_from_count(count)

        row = {"ell": ell, "M": M, "M2": M * M, "GG": GG,
               "T_ordered": T_ordered, "T_unordered": T_unordered,
               "T_diag": T_diag, "N_classes": "", "min_orbit": "",
               "max_orbit": "", "max_orbit_over_GG": ""}

        print(f"[ell={ell}] M={M}  T_ordered={T_ordered}  "
              f"T_unordered={T_unordered}  T_diag={T_diag}")

        if do_orbits:
            sizes, reps, nodeset, groups = gg_orbits(ell, count, sigmap)
            # asserts: partition consistency + orbit-stabilizer sanity
            assert sum(sizes) == T_ordered, (
                f"sum(orbit sizes)={sum(sizes)} != T_ordered={T_ordered}")
            for s in sizes:
                assert GG % s == 0, f"orbit size {s} does not divide |GG|={GG}"
                assert s <= GG, f"orbit size {s} exceeds |GG|={GG}"
            N = len(sizes)
            row.update({"N_classes": N, "min_orbit": min(sizes),
                        "max_orbit": max(sizes),
                        "max_orbit_over_GG": f"{max(sizes) / GG:.6g}"})

            # shortcut validation: BFS orbit == union-find orbit for each class
            os.makedirs(SEED_DIR, exist_ok=True)
            seeds = []
            for root, rep in reps.items():
                bfs = seed_expand(rep, ell)
                uf_size = sizes[list(reps).index(root)]
                assert len(bfs) == uf_size, (
                    f"seed_expand size {len(bfs)} != orbit size {uf_size}")
                seeds.append([int(rep[0]), int(rep[1])])
            with open(os.path.join(SEED_DIR, f"ell{ell}.json"), "w") as f:
                json.dump({"ell": ell, "n_classes": N, "seeds": seeds}, f, indent=2)

            if N == 1:
                # single seed's orbit IS the whole LP set -- and we verified it.
                assert seed_expand(reps[next(iter(reps))], ell).__len__() == T_ordered
                print(f"[ell={ell}] N_classes=1  -> single seed expands to the "
                      f"entire LP set ({T_ordered} ordered pairs).")
            else:
                print(f"[ell={ell}] N_classes={N} > 1  -> CAVEAT: a single seed "
                      f"is INCOMPLETE; it misses {N - 1} of {N} classes. "
                      f"Orbit sizes: {sorted(sizes)}")

        append_census_row(row)
    write_cost_header()


