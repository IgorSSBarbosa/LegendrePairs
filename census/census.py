# --------------------------------------------------------------------------- #
# number theory
# --------------------------------------------------------------------------- #
def euler_phi(n: int) -> int:
    result, m, p = n, n, 2
    while p * p <= m:
        if m % p == 0:
            while m % p == 0:
                m //= p
            result -= result // p
        p += 1
    if m > 1:
        result -= result // m
    return result


def group_order(ell: int) -> int:
    """|GG| = 4 * ell^2 * phi(ell)."""
    return 4 * ell * ell * euler_phi(ell)


def units(ell: int) -> list[int]:
    """The multiplicative group Z_ell^x."""
    return [k for k in range(1, ell) if gcd(k, ell) == 1]


# --------------------------------------------------------------------------- #
# signatures
# --------------------------------------------------------------------------- #
def mask_to_seq(mask: int, ell: int) -> np.ndarray:
    """+-1 sequence whose ``-1`` positions are the set bits of ``mask``."""
    u = np.ones(ell, dtype=np.int64)
    for p in range(ell):
        if (mask >> p) & 1:
            u[p] = -1
    return u


def signature(mask: int, ell: int) -> tuple[int, ...]:
    """sigma(u) = (PAF(u,1),...,PAF(u,(ell-1)/2)) as an exact integer tuple.

    Computed by FFT (O(ell log ell)); values must be integers, which we assert
    (we key dictionaries on these ints -- never on floats)."""
    u = mask_to_seq(mask, ell).astype(float)
    r = np.fft.ifft(np.abs(np.fft.fft(u)) ** 2).real
    h = (ell - 1) // 2
    s = r[1:h + 1]
    si = np.rint(s).astype(np.int64)
    if np.max(np.abs(s - si)) > 1e-6:
        raise AssertionError(f"non-integer PAF at mask={mask}, ell={ell}: {s}")
    return tuple(int(x) for x in si)


def _sig_worker(args):
    mask, ell = args
    return mask, signature(mask, ell)


def complement(sig: tuple[int, ...]) -> tuple[int, ...]:
    """(-2,...,-2) - sigma."""
    return tuple(-2 - x for x in sig)


