# STEP 2A/B -- signature census + materialized LP set (with checkpointing)
# --------------------------------------------------------------------------- #
def _ckpt_path(ell: int) -> str:
    return os.path.join(CKPT_DIR, f"ell{ell}.pkl")


def _save_ckpt(ell, count, sigmap, last_index):
    os.makedirs(CKPT_DIR, exist_ok=True)
    path = _ckpt_path(ell)
    tmp = path + ".tmp"
    with open(tmp, "wb") as f:
        pickle.dump({"ell": ell, "last_index": last_index,
                     "count": dict(count),
                     "sigmap": {k: list(v) for k, v in sigmap.items()}}, f)
    os.replace(tmp, path)               # atomic -- never a half-written ckpt


def _load_ckpt(ell):
    path = _ckpt_path(ell)
    if not os.path.exists(path):
        return None
    with open(path, "rb") as f:
        d = pickle.load(f)
    if d.get("ell") != ell:
        raise ValueError(f"checkpoint ell={d.get('ell')} != {ell}")
    count = defaultdict(int, d["count"])
    sigmap = defaultdict(list, {k: list(v) for k, v in d["sigmap"].items()})
    return count, sigmap, int(d["last_index"])


def census_signatures(ell: int, cores: int = 1, resume: bool = True,
                      progress: bool = True):
    """Enumerate normalized u, tally sigma(u); returns (count, sigmap).

    ``count[sig]`` = #sequences with that signature; ``sigmap[sig]`` = their
    bitmasks. Checkpointed every ``CHUNK`` combinations to ``ckpt/ell{ell}.pkl``
    and resumable, so a run can be stopped and restarted at any time."""
    neg = (ell - 1) // 2
    total = math.comb(ell, neg)

    count = defaultdict(int)
    sigmap = defaultdict(list)
    start = 0
    if resume:
        loaded = _load_ckpt(ell)
        if loaded is not None:
            count, sigmap, start = loaded
            if progress:
                print(f"[ell={ell}] resuming from checkpoint at index {start}")

    combos = islice(combinations(range(ell), neg), start, None)
    idx = start
    pool = None
    if cores > 1:
        import multiprocessing as mp
        pool = mp.Pool(cores)

    bar = tqdm(total=total, initial=start, desc=f"ell={ell} sigs",
               disable=not progress)
    try:
        while True:
            chunk = list(islice(combos, CHUNK))
            if not chunk:
                break
            masks = [sum(1 << p for p in combo) for combo in chunk]
            if pool is not None:
                results = pool.map(_sig_worker, [(m, ell) for m in masks])
            else:
                results = [(m, signature(m, ell)) for m in masks]
            for mask, sig in results:
                count[sig] += 1
                sigmap[sig].append(mask)
            idx += len(chunk)
            _save_ckpt(ell, count, sigmap, idx)
            if bar is not None:
                bar.update(len(chunk))
    finally:
        if pool is not None:
            pool.close()
            pool.join()
        if hasattr(bar, "close"):
            bar.close()
    return count, sigmap


def totals_from_count(count) -> tuple[int, int, int]:
    """(T_ordered, T_unordered, T_diag) from the signature histogram."""
    t_ordered = 0
    t_diag = 0
    for sig, c in count.items():
        comp = complement(sig)
        t_ordered += c * count.get(comp, 0)
        if comp == sig:
            t_diag += c
    t_unordered = (t_ordered + t_diag) // 2
    return t_ordered, t_unordered, t_diag


# --------------------------------------------------------------------------- #
# STEP 2C/D -- GG orbits over the ordered LP pair set
# --------------------------------------------------------------------------- #
def _perm_apply(mask: int, perm: list[int]) -> int:
    """Relabel the set bits of ``mask`` by ``perm`` (a position permutation)."""
    out = 0
    p = 0
    m = mask
    while m:
        if m & 1:
            out |= 1 << perm[p]
        m >>= 1
        p += 1
    return out


def _generators(ell: int):
    """Position permutations for the GG generators.

    Returns ``(shift, neg, muls)`` where ``shift`` is p->p+1, ``neg`` is p->-p,
    and ``muls`` is the list of decimation permutations p->p*k for every unit k
    (covers Z_ell^x even when it is non-cyclic, e.g. ell=15)."""
    shift = [(p + 1) % ell for p in range(ell)]
    neg = [(-p) % ell for p in range(ell)]
    muls = [[(p * k) % ell for p in range(ell)] for k in units(ell)]
    return shift, neg, muls


def _neighbors(pair, ell, gens):
    """All GG-generator images of an ordered pair ``(bu, bv)``."""
    bu, bv = pair
    shift, neg, muls = gens
    out = [
        (_perm_apply(bu, shift), bv),        # shift_u
        (bu, _perm_apply(bv, shift)),        # shift_v
        (bv, bu),                            # switch
        (bu, _perm_apply(bv, neg)),          # reverse_v
    ]
    for mul in muls:                         # decim (both members)
        out.append((_perm_apply(bu, mul), _perm_apply(bv, mul)))
    return out


class _UF:
    def __init__(self):
        self.parent = {}

    def find(self, x):
        self.parent.setdefault(x, x)
        root = x
        while self.parent[root] != root:
            root = self.parent[root]
        while self.parent[x] != root:      # path compression
            self.parent[x], x = root, self.parent[x]
        return root

    def union(self, a, b):
        ra, rb = self.find(a), self.find(b)
        if ra != rb:
            self.parent[ra] = rb


def ordered_lp_pairs(count, sigmap):
    """Yield every ordered LP pair (bu, bv) as bitmask tuples."""
    for sig, masks_u in sigmap.items():
        comp = complement(sig)
        masks_v = sigmap.get(comp)
        if not masks_v:
            continue
        for bu in masks_u:
            for bv in masks_v:
                yield (bu, bv)


def gg_orbits(ell, count, sigmap):
    """Union-find partition of the ordered LP set under GG.

    Returns ``(orbits, pairs)`` where ``orbits`` is a list of orbit sizes and
    ``pairs`` maps each orbit root -> a representative pair."""
    gens = _generators(ell)
    nodes = list(ordered_lp_pairs(count, sigmap))
    nodeset = set(nodes)
    uf = _UF()
    for pair in nodes:
        uf.find(pair)                          # register
    for pair in nodes:
        for nb in _neighbors(pair, ell, gens):
            # GG preserves the LP property, so every image must be a known node.
            if nb not in nodeset:
                raise AssertionError(
                    f"GG image {nb} of {pair} is not an LP -- generator bug")
            uf.union(pair, nb)
    groups = defaultdict(list)
    for pair in nodes:
        groups[uf.find(pair)].append(pair)
    reps = {root: members[0] for root, members in groups.items()}
    sizes = [len(m) for m in groups.values()]
    return sizes, reps, nodeset, dict(groups)


def seed_expand(seed, ell):
    """BFS from one seed over the GG generators -- NO candidate enumeration.

    Returns the full orbit (set of ordered pairs) reachable from ``seed``."""
    gens = _generators(ell)
    seen = {seed}
    frontier = [seed]
    while frontier:
        nxt = []
        for pair in frontier:
            for nb in _neighbors(pair, ell, gens):
                if nb not in seen:
                    seen.add(nb)
                    nxt.append(nb)
        frontier = nxt
    return seen


