"""Legendre-pair census via signature counting + GG-orbit structure.

For each odd length ``ell`` we

  * count all Legendre pairs exactly (a signature census over the C(ell,(ell-1)/2)
    normalized sequences -- cheap, since that binomial is <= 92378 for ell<=19), and
  * partition the pair set into orbits of the "good group" GG (coordinate
    permutations that preserve the LP property), reporting orbit sizes and
    stabilizers.

The facts the code relies on (NOT re-derived at runtime -- see README.md):

Legendre pair (normalized).  u, v in {-1,+1}^ell of odd length ell, each with
exactly (ell-1)/2 entries equal to -1 (so 1.u = 1.v = +1), satisfying
    PAF(u,j) + PAF(v,j) = -2   for all j != 0   (mod ell),
where PAF(w,j) = sum_i w_i w_{(i-j) mod ell}.

Signature form (necessary AND sufficient).  With
    sigma(u) = (PAF(u,1), ..., PAF(u,(ell-1)/2))   (integer valued),
(u,v) is an LP  <=>  sigma(v) = (-2,...,-2) - sigma(u).  So counting LPs is a
convolution of the signature histogram with its complement.

The good group GG.  |GG| = 4 * ell^2 * phi(ell).  GG acts by coordinate
permutations (hence preserves normalization), generated by
    shift_u  : (c1(u), v)             c1(w)_i = w_{i-1 mod ell}
    shift_v  : (u, c1(v))
    decim    : (d_g(u), d_g(v))        d_k(w)_i = w_{i k^{-1} mod ell}
    reverse_v: (u, d_{-1}(v))
    switch   : (v, u)
Each generator is a permutation of the ell positions; on the bitmask of "-1"
positions, shift sends p -> p+1, decimation-by-k sends p -> p*k, reversal sends
p -> -p (all mod ell).

We ENUMERATE as ground truth and use GG only to organize/validate: a single
seed's orbit equals the whole LP set ONLY when there is one class (N=1). The
code never claims otherwise -- it prints the caveat when N>1.
"""

