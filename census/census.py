def main() -> int:
    p = argparse.ArgumentParser(description="Legendre-pair census + GG orbits.")
    p.add_argument("--step", type=int, choices=[1, 2, 3], default=2,
                   help="1: group-order table; 2: census+orbits; 3: greedy (stub)")
    p.add_argument("--lmin", type=int, default=5)
    p.add_argument("--lmax", type=int, default=20)
    p.add_argument("--cores", type=int, default=1,
                   help="worker processes for the signature census")
    p.add_argument("--orbits", action="store_true",
                   help="also compute the GG-orbit partition (Step 2C/D)")
    p.add_argument("--greedy", action="store_true",
                   help="(Step 3) register the flag; raises NotImplementedError")
    p.add_argument("--quiet", action="store_true")
    args = p.parse_args()

    if args.greedy or args.step == 3:
        step3_greedy()
        return 0
    if args.step == 1:
        step1(args.lmin, args.lmax)
        return 0
    step2(args.lmin, args.lmax, cores=args.cores, do_orbits=args.orbits,
          progress=not args.quiet)
    return 0


