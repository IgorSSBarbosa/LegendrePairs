"""symmetry.py — the full Legendre-pair equivalence group, on pm1 arrays.

Decimation v[i] -> v[(d*i) mod L] (gcd(d,L)=1) has no clean action on runs, so
all decimation / reversal / swap dedup is done here on pm1 arrays over the
(small) final solution set, NOT in the RLE layer (spec §1.3).

Equivalence used for counting inequivalent Legendre pairs.  On normalized
(row-sum +1) pairs the group is generated by:
  * independent cyclic shift of each sequence  (PAF is shift-invariant),
  * a common decimation d in (Z/L)^*  (reversal is the case d = L-1),
  * swapping u <-> v,
  * negation of either sequence  (folded away by the +1 normalization).

canonical_pair returns a hashable bytes key that is constant on each class.
The SAME routine is used by the RLE driver and the independent brute force, so
their agreement (spec §3a) does not depend on this group being exactly the
published one; the literature cross-check (§3b) is what tests that.
"""
from __future__ import annotations

from math import gcd
from typing import List, Tuple

import numpy as np


def units(L: int) -> List[int]:
    """Multiplicative units of Z_L (decimation multipliers)."""
    return [d for d in range(1, L) if gcd(d, L) == 1]


def decimate(v: np.ndarray, d: int) -> np.ndarray:
    """v[i] -> v[(d*i) mod L]."""
    L = v.shape[0]
    idx = (d * np.arange(L)) % L
    return v[idx]


def least_rotation_seq(v: np.ndarray) -> np.ndarray:
    """Lexicographically least cyclic rotation of a pm1 sequence (Booth, O(L))."""
    S = np.asarray(v, dtype=np.int64)
    n = S.shape[0]
    f = [-1] * (2 * n)
    k = 0
    for j in range(1, 2 * n):
        sj = S[j % n]
        idx = j - k - 1
        i = -1 if idx < 0 else f[idx]
        while i != -1 and sj != S[(k + i + 1) % n]:
            if sj < S[(k + i + 1) % n]:
                k = j - i - 1
            i = f[i]
        if sj != S[(k + i + 1) % n]:
            if sj < S[k % n]:
                k = j
            f[j - k] = -1
        else:
            f[j - k] = i + 1
    k = k % n
    return np.concatenate((S[k:], S[:k])).astype(np.int8)


def canonical_seq(v: np.ndarray) -> bytes:
    """Canonical key of a single sequence under rotation + decimation."""
    v = np.asarray(v, dtype=np.int8)
    L = v.shape[0]
    best = None
    for d in units(L):
        key = least_rotation_seq(decimate(v, d)).tobytes()
        if best is None or key < best:
            best = key
    return best


def _reverse(v: np.ndarray) -> np.ndarray:
    L = v.shape[0]
    return v[(-np.arange(L)) % L]


def canonical_pair(u: np.ndarray, v: np.ndarray) -> Tuple[bytes, bytes]:
    """Canonical key of a Legendre pair under the full equivalence group.

    Matches the Kounias/Fletcher-Gysin-Seberry convention (their NGL-pairs):
    two pairs are equivalent under (i) swapping u<->v, (ii) cyclically shifting
    EITHER sequence, (iii) reversing EITHER sequence, (iv) decimating BOTH by a
    common amount. Since reverse(x∘d) = x∘(-d), independent reversal + common
    decimation lets each sequence use +/-d independently, so we enumerate d over
    the units and independently allow a reversal of each sequence.
    """
    u = np.asarray(u, dtype=np.int8)
    v = np.asarray(v, dtype=np.int8)
    best = None
    for d in units(u.shape[0]):
        ud = decimate(u, d)
        vd = decimate(v, d)
        u_cands = (least_rotation_seq(ud).tobytes(),
                   least_rotation_seq(_reverse(ud)).tobytes())
        v_cands = (least_rotation_seq(vd).tobytes(),
                   least_rotation_seq(_reverse(vd)).tobytes())
        a = min(u_cands)
        b = min(v_cands)
        pair = (a, b) if a <= b else (b, a)  # swap-invariance
        if best is None or pair < best:
            best = pair
    return best
